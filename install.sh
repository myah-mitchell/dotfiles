# ── GitHub release downloader ─────────────────────────────────────────────────
# Usage: download_release REPO ASSET_GLOB DEST_BIN [BINARY_IN_ARCHIVE]
# ASSET_GLOB: shell glob matching the archive filename, e.g. "bat-*-x86_64*linux*musl*.tar.gz"
# DEST_BIN:   filename to create in BIN_DIR
# BINARY_IN_ARCHIVE: path inside archive to the binary (default: same as DEST_BIN)
download_release() {
  local repo="$1" glob="$2" dest="$3" bin_in_archive="${4:-$3}"
  local key="${dest}"
  local installed
  installed=$(get_installed_version "$key")

  log "Checking ${dest}..."

  # Skip the API call entirely when already installed and not forcing update.
  # With 25+ tools and 60 unauthenticated requests/hour, making an API call for
  # every tool on every run burns the rate limit and causes tools past ~tool 10
  # to never record their version in .versions (they get "Could not fetch" and
  # return early, leaving installed="" on the next run → re-download loop).
  if [[ -n "$installed" && "$FORCE_UPDATE" == false ]]; then
    ok "${dest} already at ${installed}"
    return
  fi

  # Single API call — parse both tag_name and asset URLs from one response.
  local api_response
  api_response=$(curl -sf --connect-timeout 15 --retry 3 --retry-delay 2 \
    "${GITHUB_AUTH[@]}" "https://api.github.com/repos/${repo}/releases/latest") || true

  local latest
  latest=$(echo "$api_response" | grep -oP '"tag_name":\s*"\K[^"]+' | head -1) || true
  if [[ -z "$latest" ]]; then
    warn "Could not fetch latest version for ${repo} — skipping."
    return
  fi

  if [[ "$installed" == "$latest" && "$FORCE_UPDATE" == false ]]; then
    ok "${dest} already at ${latest}"
    return
  fi

  log "Downloading ${dest} ${latest}..."

  # Convert shell glob wildcards (*) to grep extended-regex (.*) for proper matching
  local regex="${glob//\*/.*}"

  # Find the matching asset URL from the cached API response
  local asset_url
  asset_url=$(echo "$api_response" |
    grep '"browser_download_url"' |
    grep -v '\.sha256\|\.sha512\|\.asc\|\.sig\|checksums\|\.deb\|\.rpm\|\.msi\|\.dmg\|\.pkg\|-apple-darwin\|windows\|\.exe\|android' |
    grep -iE "$regex" |
    head -1 |
    cut -d'"' -f4) || true

  if [[ -z "$asset_url" ]]; then
    # Fallback: /releases/latest may have no assets on some repos. Try the
    # releases list and take the newest release that has a matching asset.
    local releases_response
    releases_response=$(curl -sf --connect-timeout 15 --retry 3 --retry-delay 2 \
      "${GITHUB_AUTH[@]}" "https://api.github.com/repos/${repo}/releases?per_page=5") || true
    asset_url=$(echo "$releases_response" |
      grep '"browser_download_url"' |
      grep -v '\.sha256\|\.sha512\|\.asc\|\.sig\|checksums\|\.deb\|\.rpm\|\.msi\|\.dmg\|\.pkg\|-apple-darwin\|windows\|\.exe\|android' |
      grep -iE "$regex" |
      head -1 |
      cut -d'"' -f4) || true
    if [[ -n "$asset_url" ]]; then
      # Extract version from the URL for tracking
      latest=$(echo "$releases_response" | grep -oP '"tag_name":\s*"\K[^"]+' | head -1) || true
    fi
  fi

  if [[ -z "$asset_url" ]]; then
    warn "No matching asset found for ${dest} (pattern: ${glob}) — skipping."
    return
  fi

  local tmpdir
  tmpdir=$(mktemp -d)
  trap "rm -rf '$tmpdir'" RETURN

  local archive="${tmpdir}/archive"
  if ! curl -fL --connect-timeout 30 --max-time 600 --retry 2 "$asset_url" -o "$archive"; then
    warn "Download failed for ${dest} — skipping."
    return
  fi

  # Detect archive type and extract
  local extracted_binary
  if [[ "$asset_url" == *.tar.gz || "$asset_url" == *.tgz ]]; then
    tar -xzf "$archive" -C "$tmpdir"
    extracted_binary=$(find "$tmpdir" -name "$bin_in_archive" -not -name "*.gz" | head -1)
  elif [[ "$asset_url" == *.tar.xz ]]; then
    tar -xJf "$archive" -C "$tmpdir"
    extracted_binary=$(find "$tmpdir" -name "$bin_in_archive" | head -1)
  elif [[ "$asset_url" == *.zip ]]; then
    unzip -q "$archive" -d "$tmpdir"
    extracted_binary=$(find "$tmpdir" -name "$bin_in_archive" | head -1)
  else
    # Plain binary
    extracted_binary="$archive"
  fi

  if [[ -z "$extracted_binary" || ! -f "$extracted_binary" ]]; then
    warn "Could not find '${bin_in_archive}' in archive for ${dest} — skipping."
    return
  fi

  install -m 755 "$extracted_binary" "$BIN_DIR/$dest"
  set_installed_version "$key" "$latest"
  ok "${dest} installed at ${latest}"
}

# ── Node.js installer (from nodejs.org, not a GitHub release) ─────────────────
# Node is a runtime *tree* (bin/node + lib/node_modules/npm, with npm/npx as
# relative symlinks into lib), not a single binary, so download_release can't
# handle it. Installs the latest LTS straight into ~/.local/{bin,lib,include,
# share} as real files (outside the dotfiles symlink tree, so prune/link never
# touch it). This is what unblocks Mason's npm-based LSP servers (html, css,
# emmet, bash, intelephense, pyright). ~/.local/bin is already prepended ahead
# of the Windows nodejs path in zsh/.zshenv, so the Linux `npm` wins.
install_node() {
  local key="node" installed latest
  installed=$(get_installed_version "$key")

  log "Checking node..."

  # Latest LTS from the dist index, without jq: each release object ends in '}',
  # so split per object, keep those with a string "lts":"Name" (false has no
  # quote after the colon), take the newest (index is newest-first).
  latest=$(curl -sf --connect-timeout 15 --retry 3 --retry-delay 2 \
    "https://nodejs.org/dist/index.json" |
    tr '}' '\n' | grep '"lts":"' |
    grep -oP '"version":\s*"\Kv[^"]+' | head -1) || true
  if [[ -z "$latest" ]]; then
    warn "Could not determine latest Node LTS — skipping."
    return
  fi
  if [[ "$installed" == "$latest" && "$FORCE_UPDATE" == false ]]; then
    ok "node already at ${latest}"
    return
  fi

  local node_os node_arch
  case "$OS" in
  linux) node_os="linux" ;;
  darwin) node_os="darwin" ;;
  *)
    warn "Unsupported OS for Node.js (${OS}) — skipping."
    return
    ;;
  esac
  case "$ARCH" in
  x86_64) node_arch="x64" ;;
  aarch64) node_arch="arm64" ;;
  *)
    warn "Unsupported arch for Node.js (${ARCH}) — skipping."
    return
    ;;
  esac

  local base="node-${latest}-${node_os}-${node_arch}"
  local url="https://nodejs.org/dist/${latest}/${base}.tar.xz"
  local tmpdir
  tmpdir=$(mktemp -d)
  trap "rm -rf '$tmpdir'" RETURN

  log "Downloading Node.js ${latest} (${node_os}-${node_arch})..."
  if ! curl -fL --connect-timeout 30 --max-time 600 --retry 2 "$url" -o "$tmpdir/node.tar.xz"; then
    warn "Node.js download failed — skipping."
    return
  fi
  if ! tar -xJf "$tmpdir/node.tar.xz" -C "$tmpdir"; then
    warn "Node.js extract failed — skipping."
    return
  fi

  local root="$tmpdir/$base"
  if [[ ! -d "$root/bin" ]]; then
    warn "Unexpected Node.js archive layout — skipping."
    return
  fi

  # Merge into ~/.local, preserving the relative npm/npx symlinks (cp -a).
  mkdir -p "$LOCAL_BIN" "$LOCAL_SHARE" "$HOME/.local/lib" "$HOME/.local/include"
  cp -a "$root/bin/." "$LOCAL_BIN/"
  cp -a "$root/lib/." "$HOME/.local/lib/"
  [[ -d "$root/include" ]] && cp -a "$root/include/." "$HOME/.local/include/"
  [[ -d "$root/share" ]] && cp -a "$root/share/." "$LOCAL_SHARE/"

  set_installed_version "$key" "$latest"
  ok "node installed at ${latest} ($("$LOCAL_BIN/node" --version 2>/dev/null || echo '?'))"
}

# ── Claude Code CLI (native installer) ─────────────────────────────────────────
# Installs via the official native installer (curl | bash from claude.ai/install.sh),
# the same mechanism that already owns ~/.local/bin/claude as a symlink into
# ~/.local/share/claude/versions/<version> — see the cleanup_orphans() note on
# that layout for how old versions there get pruned. The installer self-updates
# in the background on its own, so this only ever bootstraps a fresh install;
# no .versions tracking here (there's nothing meaningful for us to compare
# against — the native updater manages its own version state independently of
# this script). --update runs `claude update` to force an immediate check
# rather than waiting on the background updater.
install_claude() {
  log "Checking claude..."

  if [[ -x "$LOCAL_BIN/claude" ]]; then
    if [[ "$FORCE_UPDATE" == true ]]; then
      if "$LOCAL_BIN/claude" update &>/dev/null; then
        ok "claude updated ($("$LOCAL_BIN/claude" --version 2>/dev/null || echo '?'))"
      else
        warn "claude update failed — it auto-updates in the background regardless"
      fi
    else
      ok "claude already installed ($("$LOCAL_BIN/claude" --version 2>/dev/null || echo '?'))"
    fi
    return
  fi

  log "Installing Claude Code..."
  if curl -fsSL --connect-timeout 15 --retry 2 https://claude.ai/install.sh | bash &>/dev/null; then
    ok "claude installed ($("$LOCAL_BIN/claude" --version 2>/dev/null || echo '?'))"
  else
    warn "Claude Code install failed — install manually: curl -fsSL https://claude.ai/install.sh | bash"
  fi
}

# ── claude-swap (multi-account switcher for Claude Code CLI) ──────────────────
# PyPI-only (no GitHub-release binaries) — installed via `uv tool install`,
# the exact install method the tool's own self-upgrade command (`cswap
# upgrade`) is built to detect and drive. Requires uv, downloaded into
# $BIN_DIR by the CLI_TOOLS loop above; called via that repo-tree path
# directly rather than PATH lookup, since link_package hasn't symlinked it
# into ~/.local/bin yet at this point in the script (same reasoning as the
# bat theme-cache build above). Always-latest like the rest of CLI_TOOLS, not
# pinned like ccstatusline above: nothing here parses claude-swap's output, so
# a version bump can't silently break a script the way an unreviewed
# ccstatusline bump could — `uv tool list` is a local, zero-cost check, so
# it's fine to re-run every invocation instead of gating on the .versions
# cache.
install_claude_swap() {
  if [[ ! -x "$BIN_DIR/uv" ]]; then
    warn "uv not found (uv install may have failed) — skipping claude-swap."
    return
  fi

  log "Checking claude-swap..."
  if [[ "$FORCE_UPDATE" == true ]]; then
    if "$BIN_DIR/uv" tool upgrade claude-swap &>/dev/null ||
      "$BIN_DIR/uv" tool install claude-swap &>/dev/null; then
      ok "claude-swap upgraded"
    else
      warn "claude-swap upgrade/install failed — skipping."
    fi
    return
  fi

  if "$BIN_DIR/uv" tool list 2>/dev/null | grep -q '^claude-swap'; then
    ok "claude-swap already installed"
    return
  fi

  if "$BIN_DIR/uv" tool install claude-swap &>/dev/null; then
    ok "claude-swap installed"
  else
    warn "claude-swap install failed — skipping."
  fi
}

# ── PowerShell installer (self-contained, bundles .NET; from GitHub release) ───
# The PowerShell LSP (powershell_es) just needs `pwsh` on PATH. PowerShell ships
# a self-contained tarball that bundles the .NET runtime — no separate .NET, no
# root. It's a flat app *tree* (~190 MB: pwsh + hundreds of .dlls), not a single
# binary, so it can't use download_release: extract it whole into
# ~/.local/lib/powershell and symlink pwsh into ~/.local/bin. Mason then installs
# the PowerShell Editor Services bundle (a plain download, not pip/npm) and
# powershell_es runs it via pwsh (see nvim plugins/lsp-servers.lua).
install_powershell() {
  local key="pwsh" installed latest tag
  installed=$(get_installed_version "$key")

  log "Checking pwsh..."
  tag=$(curl -sf --connect-timeout 15 --retry 3 --retry-delay 2 \
    "${GITHUB_AUTH[@]}" "https://api.github.com/repos/PowerShell/PowerShell/releases/latest" |
    grep -oP '"tag_name":\s*"\K[^"]+' | head -1) || true
  if [[ -z "$tag" ]]; then
    warn "Could not determine latest PowerShell release — skipping."
    return
  fi
  latest="${tag#v}"
  if [[ "$installed" == "$latest" && "$FORCE_UPDATE" == false ]]; then
    ok "pwsh already at ${latest}"
    return
  fi

  local ps_os ps_arch
  case "$OS" in
  linux) ps_os="linux" ;;
  darwin) ps_os="osx" ;;
  *)
    warn "Unsupported OS for PowerShell (${OS}) — skipping."
    return
    ;;
  esac
  case "$ARCH" in
  x86_64) ps_arch="x64" ;;
  aarch64) ps_arch="arm64" ;;
  *)
    warn "Unsupported arch for PowerShell (${ARCH}) — skipping."
    return
    ;;
  esac

  local asset="powershell-${latest}-${ps_os}-${ps_arch}.tar.gz"
  local url="https://github.com/PowerShell/PowerShell/releases/download/${tag}/${asset}"
  local tmpdir
  tmpdir=$(mktemp -d)
  trap "rm -rf '$tmpdir'" RETURN

  log "Downloading PowerShell ${latest} (${ps_os}-${ps_arch})..."
  if ! curl -fL --connect-timeout 30 --max-time 600 --retry 2 "$url" -o "$tmpdir/pwsh.tar.gz"; then
    warn "PowerShell download failed — skipping."
    return
  fi

  # Flat archive → extract the whole tree into a dedicated dir (replace on update).
  local dest="$HOME/.local/lib/powershell"
  rm -rf "$dest"
  mkdir -p "$dest" "$LOCAL_BIN"
  if ! tar -xzf "$tmpdir/pwsh.tar.gz" -C "$dest"; then
    warn "PowerShell extract failed — skipping."
    return
  fi
  chmod +x "$dest/pwsh"
  ln -sf "$dest/pwsh" "$LOCAL_BIN/pwsh"

  set_installed_version "$key" "$latest"
  ok "pwsh installed at ${latest} ($("$LOCAL_BIN/pwsh" -NoProfile -Command '$PSVersionTable.PSVersion.ToString()' 2>/dev/null || echo '?'))"
}

# ── Cargo installer ───────────────────────────────────────────────────────────
# Usage: cargo_install CRATE DEST_BIN
# Installs to dotfiles bin dir via cargo (symlinked to ~/.local/bin by link_package).
# Checks crates.io for the latest version to avoid unnecessary recompiles.
cargo_install() {
  local crate="$1" dest="$2"
  local cargo_bin="$HOME/.cargo/bin/cargo"
  log "Checking ${dest} (cargo)..."
  if [[ ! -x "$cargo_bin" ]]; then
    warn "${dest}: cargo not available — skipping"
    return
  fi
  local latest
  latest=$(curl -sf --connect-timeout 15 \
    -H "User-Agent: dotfiles-install/1.0" \
    "https://crates.io/api/v1/crates/${crate}" |
    grep -oP '"newest_version"\s*:\s*"\K[^"]+' | head -1) || true
  if [[ -z "$latest" ]]; then
    warn "Could not fetch latest version for ${crate} — skipping"
    return
  fi
  local installed
  installed=$(get_installed_version "$dest")
  if [[ -z "$installed" ]]; then
    installed=$("$cargo_bin" install --list --root "$DOTFILES/bin/.local" 2>/dev/null |
      grep -oP "^${crate} v\K[0-9][^:]+") || true
    [[ -n "$installed" ]] && set_installed_version "$dest" "$installed"
  fi
  if [[ "$installed" == "$latest" && "$FORCE_UPDATE" == false ]]; then
    ok "${dest} already at ${latest}"
    return
  fi
  log "Installing ${dest} ${latest} via cargo (compiling from source)..."
  local -a flags=(--root "$DOTFILES/bin/.local" --force)
  # Try --locked first: if the crate published a Cargo.lock it pins transitive
  # deps (e.g. interprocess 1.x) that may otherwise resolve to a breaking version.
  local install_ok=false
  if "$cargo_bin" install "$crate" --locked "${flags[@]}" 2>&1; then
    install_ok=true
  else
    log "Retrying ${dest} without --locked..."
    if "$cargo_bin" install "$crate" "${flags[@]}" 2>&1; then
      install_ok=true
    fi
  fi
  if [[ "$install_ok" == true ]]; then
    set_installed_version "$dest" "$latest"
    ok "${dest} installed at ${latest}"
  else
    warn "cargo install ${crate} failed — skipping"
  fi
}

# ── Generic tool installer ────────────────────────────────────────────────────
# Row format (pipe-separated):
#   dest | crate | repo | os | arch | glob | bin
# os:   linux | darwin
# arch: x86_64 | aarch64 | * (matches any arch for that os)
# crate: cargo crate name, or - if not available via cargo
# bin:  binary name inside archive; defaults to dest when -
# One row per supported platform variant.
declare -A _cargo_done=()
install_tool() {
  local dest crate repo os arch glob bin
  IFS='|' read -r dest crate repo os arch glob bin <<<"$1"
  [[ "$bin" == "-" ]] && bin="$dest"

  if [[ "$USE_CARGO" == true && "$crate" != "-" ]]; then
    if [[ -z "${_cargo_done[$dest]+x}" ]]; then
      cargo_install "$crate" "$dest"
      _cargo_done[$dest]=1
    fi
    return
  fi

  if [[ "$OS" == "$os" ]] && [[ "$arch" == "*" || "$ARCH" == "$arch" ]]; then
    download_release "$repo" "$glob" "$dest" "$bin"
  fi
}

